#!/usr/bin/env node
// Re-sync plan specs from /workspace/belmore/gla-plans.json (GLA Architecture).
//   node scripts/import-gla-plans.mjs [path]
// Writes src/data/plans.generated.ts. Specs only: never copy GLA images,
// renderings, or marketing text into this repo (no permission yet).
import { readFileSync, writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const src = process.argv[2] ?? "/workspace/belmore/gla-plans.json";
const raw = JSON.parse(readFileSync(src, "utf8"));

const storiesLabel = (n) => (n === 1 ? "One story" : n === 2 ? "Two story" : `${n} story`);
const garageLabel = (g) => {
  const m = String(g ?? "").match(/^(\d+)\s*bays?$/i);
  return m ? `${m[1]}-car` : String(g ?? "");
};
const slugOf = (p) =>
  p.name
    .replace(/^The\s+/i, "")
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/(^-|-$)/g, "");

const plans = raw.map((p, i) => ({
  slug: slugOf(p),
  sort: i + 1,
  name: p.name,
  planNumber: String(p.planNumber ?? ""),
  category: String(p.category ?? ""),
  beds: Number(p.beds),
  baths: String(p.baths),
  sqft: Number(p.sqft),
  sqftFirst: p.sqftByFloor?.first ?? "",
  sqftSecond: p.sqftByFloor?.second ?? "",
  stories: storiesLabel(Number(p.stories)),
  garage: garageLabel(p.garage),
  width: String(p.width ?? ""),
  depth: String(p.depth ?? ""),
  style: p.style ?? "",
  glaUrl: String(p.glaUrl ?? ""),
  notes: String(p.notes ?? ""),
}));

const out = `// GENERATED by scripts/import-gla-plans.mjs from ${src}. Do not edit by hand.
// Specs copied from GLA Architecture's published spec tables. No GLA images.
export type GlaPlanSpec = {
  slug: string;
  sort: number;
  name: string;
  planNumber: string;
  category: string;
  beds: number;
  baths: string;
  sqft: number;
  sqftFirst: string;
  sqftSecond: string;
  stories: string;
  garage: string;
  width: string;
  depth: string;
  style: string;
  glaUrl: string;
  notes: string;
};

export const glaPlanSpecs: GlaPlanSpec[] = ${JSON.stringify(plans, null, 2)};
`;
writeFileSync(join(root, "src/data/plans.generated.ts"), out);
console.log(`Imported ${plans.length} plans: ${plans.map((p) => p.slug).join(", ")}`);
