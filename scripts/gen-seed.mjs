#!/usr/bin/env node
// Writes migrations/0005_seed_content.sql from the static defaults in
// src/data/site.ts (lots 801–807 + plat figures, GLA plans).
//   node scripts/gen-seed.mjs
// Inserts use "on conflict do nothing", so owner edits made in /admin are never
// overwritten. Text blocks are not seeded: the DB stores only owner overrides
// and everything else falls back to src/data/copy.generated.ts, so a copy
// re-sync shows up without a migration.
import { createJiti } from "jiti";
import { writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const jiti = createJiti(import.meta.url, { alias: { "@": join(root, "src") } });
const { phaseLots, plans } = await jiti.import(join(root, "src/data/site.ts"));

const q = (v) => (v === null || v === undefined ? "null" : typeof v === "number" || typeof v === "boolean" ? String(v) : `'${String(v).replace(/'/g, "''")}'`);

let out = `-- GENERATED by scripts/gen-seed.mjs. Seeds lots and plans from the static
-- defaults; never overwrites rows that already exist.\n\n`;
phaseLots.forEach((l, i) => {
  out += `insert into lots (id, sort, phase, street, note, area_sqft, area_acres, frontage, depth, status, price_text, premium)
values (${[l.id, i + 1, "1", l.street, l.note, l.areaSqft || null, l.areaAcres || null, l.frontage, l.depth, l.status, l.priceText, l.premium].map(q).join(", ")})
on conflict (id) do nothing;\n`;
});
out += "\n";
for (const p of plans) {
  out += `insert into plans (slug, sort, hidden, name, plan_number, beds, baths, sqft, sqft_first, sqft_second, stories, garage, width, depth, footprint, style, price_text, architect, gla_url, rendering_image, rendering_alt, floor_plan_image, images_pending)
values (${[p.slug, p.sort, p.hidden, p.name, p.planNumber, p.beds, p.baths, p.sqft, p.sqftFirst, p.sqftSecond, p.stories, p.garage, p.width, p.depth, p.footprint, p.style, p.priceText, p.architect, p.glaUrl, p.renderingImage, p.renderingAlt, p.floorPlanImage, p.imagesPending].map(q).join(", ")})
on conflict (slug) do nothing;\n`;
}
writeFileSync(join(root, "migrations/0005_seed_content.sql"), out);
console.log(`Wrote migrations/0005_seed_content.sql (${phaseLots.length} lots, ${plans.length} plans)`);
