#!/usr/bin/env node
// Re-sync site copy from Quill's markdown files.
//
//   node scripts/import-copy.mjs [copyDir]      (default /workspace/belmore/copy)
//
// Each block in copy/*.md is a key in a code span on its own line (optionally
// followed by a "(NN chars)" note), then the paste-ready text up to the next
// blank line. "> Forge:" notes, headings and other prose are ignored.
// fact-sheet.md and placeholders.md are reference docs, not page copy.
//
// Output: src/data/copy.generated.ts (static defaults) and
// migrations/0005_seed_content.sql is NOT touched; instead run
// `node scripts/gen-seed.mjs` after this to refresh the seed. Already-deployed
// databases pick up new defaults for any key an owner has not edited, because
// public pages merge DB rows over these defaults and the admin "reset" action
// restores the default.
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const dir = process.argv[2] ?? "/workspace/belmore/copy";
const SKIP = new Set(["fact-sheet.md", "placeholders.md"]);
const KEY_RE = /^`([a-z0-9][a-z0-9._-]*)`(?:\s*\(.*\))?\s*$/;

const out = {};
const order = [];
const dupes = [];
for (const file of readdirSync(dir)
  .filter((f) => f.endsWith(".md") && !SKIP.has(f))
  .sort()) {
  const lines = readFileSync(join(dir, file), "utf8").split(/\r?\n/);
  for (let i = 0; i < lines.length; i++) {
    const m = lines[i].match(KEY_RE);
    if (!m) continue;
    const key = m[1];
    const body = [];
    let j = i + 1;
    while (j < lines.length && lines[j].trim() === "") j++;
    for (; j < lines.length && lines[j].trim() !== ""; j++) {
      if (KEY_RE.test(lines[j]) || lines[j].startsWith("#") || lines[j].startsWith(">")) break;
      body.push(lines[j].trim());
    }
    if (key in out) dupes.push(`${key} (${file})`);
    else order.push(key);
    out[key] = body.join(" ");
  }
}

// Host-specific wording in the source copy that the portable site replaces
// (the copy files still name the old preview host).
const HOST_FIXES = [[/belmoreestates\.grok\.me/g, "the Belmore Estates website"]];
for (const k of order) for (const [re, to] of HOST_FIXES) out[k] = out[k].replace(re, to);

const header = `// GENERATED by scripts/import-copy.mjs from ${dir}. Do not edit by hand:
// edit the copy .md files (or override in /admin) and re-run the script.
`;
const body = `export const copyDefaults: Record<string, string> = {\n${order
  .map((k) => `  ${JSON.stringify(k)}: ${JSON.stringify(out[k])},`)
  .join("\n")}\n};\n`;
writeFileSync(join(root, "src/data/copy.generated.ts"), header + body);
console.log(`Imported ${order.length} keys from ${dir}`);
if (dupes.length) console.warn(`Duplicate keys (last one wins): ${dupes.join(", ")}`);
const empty = order.filter((k) => !out[k]);
if (empty.length) console.warn(`Empty keys: ${empty.join(", ")}`);
