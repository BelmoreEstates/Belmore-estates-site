#!/usr/bin/env python3
"""Responsive WebP variants for the bundled stock photos (Core Web Vitals).

Run from the repo root after adding or replacing a JPG in public/images/:
    python3 scripts/optimize-images.py
Writes public/images/opt/<name>-<width>.webp and src/data/image-variants.ts
(the manifest the <Img> component reads for srcset + intrinsic size).
The original JPGs stay as the fallback and are never modified. Needs Pillow.
"""
import json, pathlib
from PIL import Image

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / "public" / "images"
OUT = SRC / "opt"
WIDTHS = (640, 1024, 1600)
OUT.mkdir(exist_ok=True)
manifest = {}
for jpg in sorted(SRC.glob("*.jpg")):
    im = Image.open(jpg).convert("RGB")
    w, h = im.size
    variants = []
    for target in sorted({min(t, w) for t in WIDTHS}):
        out = OUT / f"{jpg.stem}-{target}.webp"
        im.resize((target, round(h * target / w)), Image.LANCZOS).save(out, "WEBP", quality=72, method=6)
        variants.append({"w": target, "src": f"/images/opt/{out.name}"})
    manifest[f"/images/{jpg.name}"] = {"width": w, "height": h, "webp": variants}
ts = (
    "// Generated by scripts/optimize-images.py. Do not edit by hand.\n"
    "export type ImageVariants = {\n  width: number;\n  height: number;\n"
    "  webp: { w: number; src: string }[];\n};\n\n"
    "export const IMAGE_VARIANTS: Record<string, ImageVariants> = "
    + json.dumps(manifest, indent=2)
    + ";\n"
)
(ROOT / "src" / "data" / "image-variants.ts").write_text(ts)
for k, v in manifest.items():
    print(k, v["width"], "x", v["height"], [x["w"] for x in v["webp"]])
